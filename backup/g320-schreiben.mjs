import { chromium } from '@playwright/test'
import { wortFuer } from '../tools/konten.mjs'
const b = await chromium.launch()
const s = await b.newPage({ viewport: { width: 1440, height: 1700 } })
await s.goto('http://127.0.0.1:3200/login', { waitUntil: 'networkidle' })
await s.fill('input[type="email"]', 'dev@lumeos.app')
await s.fill('input[type="password"]', wortFuer('dev@lumeos.app'))
await s.click('button[type="submit"]')
await s.waitForURL(u => !u.pathname.includes('login'), { timeout: 30000 })
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=planner', { waitUntil: 'networkidle' })
await s.waitForTimeout(2600)

await s.locator('button[aria-label^="Eintrag hinzufügen"]').first().click()
await s.waitForTimeout(900)
await s.locator('select').filter({ hasText: 'Rezept' }).first().selectOption('bls')
await s.waitForTimeout(500)
await s.getByRole('button', { name: /Suchen/ }).first().click()
await s.waitForTimeout(700)
await s.fill('[role="dialog"] input[aria-label="Lebensmittel suchen"]', 'hammel')
await s.waitForTimeout(1800)
await s.locator('[role="dialog"] tbody tr').first().locator('button').click()
await s.waitForTimeout(1200)
await s.locator('[role="dialog"] input[aria-label="Menge in Gramm"]').fill('150')
await s.waitForTimeout(500)
// Eintragen -> Modal schliesst, Feld ist gefuellt
await s.getByRole('button', { name: 'Eintragen' }).click()
await s.waitForTimeout(1000)
console.log(`Modal zu: ${await s.locator('[role="dialog"][aria-label="Lebensmittel suchen"]').count() === 0 ? 'ja' : 'NEIN'}`)
const feld = s.locator('input[aria-label="Gewähltes Lebensmittel"]')
console.log(`Feld gefuellt: ${JSON.stringify(await feld.inputValue())}`)
const mf = s.locator('input[type="number"]').last()
console.log(`Menge uebernommen: ${await mf.inputValue()}`)
// Jetzt speichern
const knoepfe = await s.locator('.v2-planner-form button').allInnerTexts()
console.log(`Knoepfe im Formular: ${JSON.stringify(knoepfe)}`)
const speichern = s.locator('.v2-planner-form button').filter({ hasText: /Hinzuf|bernehmen/ }).first()
console.log(`Speichern gesperrt: ${await speichern.isDisabled()}`)
console.log(`Grund: ${JSON.stringify(await speichern.getAttribute('title'))}`)
await speichern.click()
await s.waitForTimeout(2200)
const t = await s.locator('body').innerText()
console.log(`Fehler am Schirm: ${t.includes('Fehler') ? 'JA' : 'nein'}`)
await s.screenshot({ path: 'backup/g320-geschrieben.png' })
await b.close()
