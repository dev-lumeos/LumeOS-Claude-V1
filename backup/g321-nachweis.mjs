import { chromium } from '@playwright/test'
import { wortFuer } from '../tools/konten.mjs'
const b = await chromium.launch()
const s = await b.newPage({ viewport: { width: 1440, height: 1700 } })
await s.goto('http://127.0.0.1:3200/login', { waitUntil: 'networkidle' })
await s.fill('input[type="email"]', 'dev@lumeos.app')
await s.fill('input[type="password"]', wortFuer('dev@lumeos.app'))
await s.click('button[type="submit"]')
await s.waitForURL(u => !u.pathname.includes('login'), { timeout: 30000 })
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=planner', { waitUntil: 'networkidle' })
await s.waitForTimeout(2600)
await s.locator('button[aria-label^="Eintrag hinzufügen"]').first().click()
await s.waitForTimeout(900)
await s.locator('select').filter({ hasText: 'Rezept' }).first().selectOption('bls')
await s.waitForTimeout(600)

console.log('── 1. Feld ──────────────────────────────')
console.log(`readOnly-Eingabefelder: ${await s.locator('input[aria-label="Gewähltes Lebensmittel"]').count()} (soll 0)`)
const knopf = s.locator('[data-probe="lebensmittel-waehlen"]')
console.log(`Knopf da: ${await knopf.count()}, Text: ${JSON.stringify(await knopf.innerText())}`)
await knopf.click()
await s.waitForTimeout(800)
const fokus = await s.evaluate(() => document.activeElement?.getAttribute('aria-label'))
console.log(`Fokus nach Öffnen: ${JSON.stringify(fokus)}`)

console.log('\n── 3. Spalten ───────────────────────────')
await s.fill('[role="dialog"] input[aria-label="Lebensmittel suchen"]', 'banane')
await s.waitForTimeout(2200)
const tab = s.locator('[role="dialog"] table')
console.log(`class: ${await tab.getAttribute('class')}, display: ${await tab.evaluate(n => getComputedStyle(n).display)}`)
console.log(`Treffer: ${await s.locator('[role="dialog"] tbody tr').count()} · ${await s.locator('[data-probe="trefferzahl"]').innerText()}`)
const kopf = await s.locator('[role="dialog"] thead').boundingBox()
const z1 = await s.locator('[role="dialog"] tbody tr').first().boundingBox()
const z8 = await s.locator('[role="dialog"] tbody tr').nth(7).boundingBox()
console.log(`thead y=${kopf.y.toFixed(0)} · Zeile1 y=${z1.y.toFixed(0)} · Zeile8 y=${z8.y.toFixed(0)}`)
console.log(`Kopf oben: ${kopf.y < z1.y ? 'JA' : 'NEIN'}`)
// Werte getrennt und rechtsbuendig?
const zellen = s.locator('[role="dialog"] tbody tr').first().locator('td')
for (const i of [2,3,4,5]) {
  const c = zellen.nth(i)
  const bb = await c.boundingBox()
  const al = await c.evaluate(n => getComputedStyle(n).textAlign)
  console.log(`  Spalte ${i}: "${(await c.innerText()).trim()}" x=${bb.x.toFixed(0)} b=${bb.width.toFixed(0)} align=${al}`)
}
await s.screenshot({ path: 'backup/g321-nachher.png' })

console.log('\n── 2. Bewegbar ──────────────────────────')
const kasten = s.locator('[data-probe="modal-kasten"]')
const vor = await kasten.boundingBox()
const leiste = s.locator('[data-probe="titelleiste"]')
const lb = await leiste.boundingBox()
await s.mouse.move(lb.x + 100, lb.y + 10)
await s.mouse.down()
await s.mouse.move(lb.x + 100 - 220, lb.y + 10 + 160, { steps: 12 })
await s.mouse.up()
await s.waitForTimeout(400)
const nach = await kasten.boundingBox()
console.log(`vorher  x=${vor.x.toFixed(0)} y=${vor.y.toFixed(0)}`)
console.log(`nachher x=${nach.x.toFixed(0)} y=${nach.y.toFixed(0)}`)
console.log(`verschoben um dx=${(nach.x-vor.x).toFixed(0)} dy=${(nach.y-vor.y).toFixed(0)}`)
console.log(`Modal noch offen: ${await kasten.count() ? 'ja' : 'NEIN — es hat geschlossen'}`)
// Bleibt es liegen?
await s.waitForTimeout(600)
const spaeter = await kasten.boundingBox()
console.log(`Position bleibt: ${Math.abs(spaeter.x-nach.x) < 2 && Math.abs(spaeter.y-nach.y) < 2 ? 'ja' : 'NEIN'}`)
console.log(`Zurücksetzen-Knopf: ${await s.getByRole('button', { name: 'Zurücksetzen' }).count()}`)
await s.screenshot({ path: 'backup/g321-verschoben.png' })
await b.close()
