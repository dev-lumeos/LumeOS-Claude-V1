import { chromium } from '@playwright/test'
import { wortFuer } from '../tools/konten.mjs'
const b = await chromium.launch()
const s = await b.newPage({ viewport: { width: 1440, height: 1700 } })
await s.goto('http://127.0.0.1:3200/login', { waitUntil: 'networkidle' })
await s.fill('input[type="email"]', 'dev@lumeos.app')
await s.fill('input[type="password"]', wortFuer('dev@lumeos.app'))
await s.click('button[type="submit"]')
await s.waitForURL(u => !u.pathname.includes('login'), { timeout: 30000 })
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=rezepte', { waitUntil: 'networkidle' })
await s.waitForTimeout(2800)
await s.getByRole('button', { name: 'Bearbeiten' }).first().click()
await s.waitForTimeout(1800)

console.log('── G-325: Zutatenzeilen ─────────────────')
const zeilen = s.locator('[data-probe="zutat-zeile"]')
const n = await zeilen.count()
console.log(`Zeilen: ${n}`)
for (let i = 0; i < Math.min(3, n); i++) {
  console.log(`  ${JSON.stringify((await zeilen.nth(i).innerText()).replace(/\n/g,' · '))}`)
}
const feld = s.locator('input[aria-label^="Menge "]').first()
console.log(`Grammfeld-Breite: ${(await feld.boundingBox()).width.toFixed(0)} px (vorher 80)`)
console.log(`Makro-Blöcke: ${await s.locator('[data-probe="zutat-makros"]').count()}`)
await s.screenshot({ path: 'backup/g325-nachher.png' })

console.log('\n── Menge ändern ─────────────────────────')
const vorText = await zeilen.first().innerText()
const vorSumme = await s.locator('body').innerText()
await feld.fill('300')
await s.waitForTimeout(700)
const nachText = await zeilen.first().innerText()
console.log(`vorher : ${JSON.stringify(vorText.replace(/\n/g,' · '))}`)
console.log(`nachher: ${JSON.stringify(nachText.replace(/\n/g,' · '))}`)
console.log(`Werte ändern sich: ${vorText !== nachText ? 'JA' : 'NEIN'}`)
await s.screenshot({ path: 'backup/g325-geaendert.png' })

console.log('\n── G-323: das Modal ─────────────────────')
const knopf = s.locator('[data-probe="zutat-suchen"]')
console.log(`Zutat-suchen-Knopf: ${await knopf.count()} · ${JSON.stringify(await knopf.innerText())}`)
await knopf.click()
await s.waitForTimeout(900)
console.log(`Modal offen: ${await s.locator('[role="dialog"][aria-label="Lebensmittel suchen"]').count()}`)
console.log(`Sortierknöpfe: ${await s.locator('[role="dialog"] button[aria-pressed]').count()}`)
const ktx = await s.locator('[data-probe="tageskontext"]').innerText().catch(() => '-')
console.log(`Kontext: ${JSON.stringify(ktx)}`)
await s.fill('[role="dialog"] input[aria-label="Lebensmittel suchen"]', 'banane')
await s.waitForTimeout(2200)
console.log(`Treffer: ${await s.locator('[role="dialog"] tbody tr').count()} · ${await s.locator('[data-probe="trefferzahl"]').innerText()}`)
await s.locator('[role="dialog"] tbody tr').first().locator('button').click()
await s.waitForTimeout(1300)
console.log(`Kontext bei Menge: ${JSON.stringify(await s.locator('[data-probe="tageskontext"]').innerText())}`)
await s.screenshot({ path: 'backup/g323-modal.png' })
await s.locator('[role="dialog"] input[aria-label="Menge in Gramm"]').fill('150')
await s.waitForTimeout(600)
console.log(`Vorschau: ${JSON.stringify((await s.locator('[data-probe="vorschau"]').innerText()).replace(/\n/g,' '))}`)
await s.getByRole('button', { name: 'Eintragen' }).click()
await s.waitForTimeout(1200)
console.log(`\nZeilen nach dem Eintragen: ${await zeilen.count()} (vorher ${n})`)
console.log(`letzte Zeile: ${JSON.stringify((await zeilen.last().innerText()).replace(/\n/g,' · '))}`)
await s.screenshot({ path: 'backup/g323-nachher.png' })
await b.close()
