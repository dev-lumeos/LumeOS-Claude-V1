import { chromium } from '@playwright/test'
import { wortFuer } from '../tools/konten.mjs'
const b = await chromium.launch()
const s = await b.newPage({ viewport: { width: 1440, height: 2200 } })
await s.goto('http://127.0.0.1:3200/login', { waitUntil: 'networkidle' })
await s.fill('input[type="email"]', 'dev@lumeos.app')
await s.fill('input[type="password"]', wortFuer('dev@lumeos.app'))
await s.click('button[type="submit"]')
await s.waitForURL(u => !u.pathname.includes('login'), { timeout: 30000 })

console.log('══ 1a · Tagebuch: das geteilte Modal ═══════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=diary', { waitUntil: 'networkidle' })
await s.waitForTimeout(3000)
await s.locator('button[aria-label="Position hinzufuegen"]').first().click()
await s.waitForTimeout(900)
console.log(`  Modal: ${await s.locator('[role="dialog"][aria-label="Lebensmittel suchen"]').count()}`)
console.log(`  Sortierknöpfe: ${await s.locator('[role="dialog"] button[aria-pressed]').count()} (vorher 2)`)
await s.fill('[role="dialog"] input[aria-label="Lebensmittel suchen"]', 'banane')
await s.waitForTimeout(2200)
console.log(`  Treffer: ${await s.locator('[role="dialog"] tbody tr').count()} · ${await s.locator('[data-probe="trefferzahl"]').innerText()}`)
console.log(`  Kontext: ${JSON.stringify((await s.locator('[data-probe="tageskontext"]').innerText().catch(()=>'—')).slice(0,60))}`)
await s.screenshot({ path: 'backup/g331-diary.png' })
await s.keyboard.press('Escape')

console.log('\n══ 1b · Vorlieben: Suche ohne prefs ════════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=prefs', { waitUntil: 'networkidle' })
await s.waitForTimeout(3200)
const feld = s.locator('input[placeholder*="Lebensmittel"], input[aria-label*="Lebensmittel"]').first()
if (await feld.count()) {
  await feld.fill('nuss')
  await s.waitForTimeout(2000)
  const t = await s.locator('body').innerText()
  const i = t.indexOf('nuss')
  console.log(`  Treffer sichtbar: ${t.slice(i, i+220).split('\n').filter(x=>x.trim()).slice(1,5).join(' | ')}`)
}
await s.screenshot({ path: 'backup/g331-prefs.png' })

console.log('\n══ 2 · Planner: kein toter Knopf ═══════════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=planner', { waitUntil: 'networkidle' })
await s.waitForTimeout(2600)
const t2 = await s.locator('body').innerText()
console.log(`  "nicht Teil dieses Auftrags": ${t2.includes('nicht Teil dieses Auftrags') ? 'NOCH DA' : 'weg'}`)
console.log(`  Verweis auf die Werkbank: ${await s.locator('[data-probe="plan-anlegen-verweis"]').count()}`)

console.log('\n══ 3 · Meal plans: die Vorschau ════════════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=plans', { waitUntil: 'networkidle' })
await s.waitForTimeout(3000)
const vk = s.locator('[data-probe="vorschau-knopf"]')
console.log(`  Vorschau-Knöpfe: ${await vk.count()}`)
const urlVor = s.url()
await vk.first().click()
await s.waitForTimeout(2200)
console.log(`  Fenster offen: ${await s.locator('[data-probe="plan-vorschau"]').count()}`)
console.log(`  Tage geladen: ${await s.locator('[data-probe="vorschau-tage"] > div').count()}`)
console.log(`  URL unverändert: ${s.url() === urlVor ? 'ja' : 'NEIN — ' + s.url()}`)
const inhalt = await s.locator('[data-probe="plan-vorschau"]').innerText()
console.log(`  Inhalt: ${JSON.stringify(inhalt.replace(/\n/g,' | ').slice(0,150))}`)
await s.screenshot({ path: 'backup/g331-vorschau.png' })
await b.close()
