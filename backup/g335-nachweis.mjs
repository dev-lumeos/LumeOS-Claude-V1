import { chromium } from '@playwright/test'
import { wortFuer } from '../tools/konten.mjs'
const b = await chromium.launch()
const s = await b.newPage({ viewport: { width: 1440, height: 2400 } })
await s.goto('http://127.0.0.1:3200/login', { waitUntil: 'networkidle' })
await s.fill('input[type="email"]', 'dev@lumeos.app')
await s.fill('input[type="password"]', wortFuer('dev@lumeos.app'))
await s.click('button[type="submit"]')
await s.waitForURL(u => !u.pathname.includes('login'), { timeout: 30000 })

console.log('══ Befund 1 · Ghost-Karten ═════════════════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=diary', { waitUntil: 'networkidle' })
await s.waitForTimeout(3200)
const t = await s.locator('body').innerText()
console.log(`  "Breakfast" im Tagebuch: ${t.includes('Breakfast') ? 'NOCH DA' : 'weg'}`)
console.log(`  Kartennamen: ${JSON.stringify(await s.locator('[data-probe="karten-name"]').allInnerTexts())}`)
const gh = t.match(/aus deinem Plan/g)
console.log(`  Ghost-Karten: ${gh ? gh.length : 0}`)

console.log('\n══ Befund 2 · Pulldown ════════════════════')
await s.locator('[data-probe="freie-mahlzeit-oeffnen"]').click()
await s.waitForTimeout(600)
const opts = await s.locator('[data-probe="freie-art"] option').allInnerTexts()
console.log(`  Auswahl: ${JSON.stringify(opts)}`)

console.log('\n══ Verschmelzung · Preferences ════════════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=prefs', { waitUntil: 'networkidle' })
await s.waitForTimeout(3200)
const p = await s.locator('body').innerText()
console.log(`  "Mahlzeitenstruktur": ${p.includes('Mahlzeitenstruktur') ? 'NOCH DA' : 'weg'}`)
console.log(`  "Hauptmahlzeiten": ${p.includes('Hauptmahlzeiten') ? 'NOCH DA' : 'weg'}`)
console.log(`  Slot-Zeilen: ${await s.locator('[data-probe="slot-zeile"]').count()}`)
console.log(`  Vorkochen: ${await s.locator('[data-probe="meal-prep-ok"]').count()}`)
console.log(`  Notizen: ${await s.locator('[data-probe="planner-notes"]').count()}`)
await s.screenshot({ path: 'backup/g335-prefs.png', fullPage: true })
await b.close()
