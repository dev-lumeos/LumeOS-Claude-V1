import { chromium } from '@playwright/test'
import { wortFuer } from '../tools/konten.mjs'
const b = await chromium.launch()
const s = await b.newPage({ viewport: { width: 1440, height: 1800 } })
await s.goto('http://127.0.0.1:3200/login', { waitUntil: 'networkidle' })
await s.fill('input[type="email"]', 'dev@lumeos.app')
await s.fill('input[type="password"]', wortFuer('dev@lumeos.app'))
await s.click('button[type="submit"]')
await s.waitForURL(u => !u.pathname.includes('login'), { timeout: 30000 })

console.log('══ DETAILANSICHT ═══════════════════════════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=rezepte', { waitUntil: 'networkidle' })
await s.waitForTimeout(2600)
await s.getByRole('button', { name: 'Ansehen' }).first().click()
await s.waitForTimeout(1500)
const dz = s.locator('[data-probe="detail-zutat"]')
console.log(`Zutatzeilen: ${await dz.count()}`)
for (let i = 0; i < Math.min(3, await dz.count()); i++) {
  console.log(`  ${JSON.stringify((await dz.nth(i).innerText()).replace(/\n/g, ' · '))}`)
}
const dv = s.locator('[data-probe="vorschau-block"]')
console.log(`Vorschau-Block: ${await dv.count()} · Trenner: ${await s.locator('[data-probe="spaltentrenner"]').count()}`)
if (await dv.count()) console.log(`  ${JSON.stringify((await dv.first().innerText()).replace(/\n/g, ' · '))}`)
await s.screenshot({ path: 'backup/g326-detail-nachher.png' })

console.log('\n══ EDITOR ══════════════════════════════════')
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=rezepte', { waitUntil: 'networkidle' })
await s.waitForTimeout(1800)
await s.getByRole('button', { name: 'Bearbeiten' }).first().click()
await s.waitForTimeout(1600)
const nb = await s.locator('input[aria-label="Rezeptname"]').boundingBox()
const fb = await s.locator('[data-probe="kopf-felder"]').boundingBox()
console.log(`Namensfeld:  x=${nb.x.toFixed(0)} b=${nb.width.toFixed(0)}`)
console.log(`vier Felder: x=${fb.x.toFixed(0)} b=${fb.width.toFixed(0)}`)
console.log(`gleich breit: ${Math.abs(nb.width - fb.width) < 3 ? 'JA' : `NEIN (${(nb.width-fb.width).toFixed(0)} px Unterschied)`}`)

const g = s.locator('input[aria-label^="Menge "]').first()
await g.fill('440')
await s.waitForTimeout(500)
const gm = await g.evaluate(n => ({ b: n.clientWidth, s: n.scrollWidth, v: n.value }))
console.log(`Grammfeld: Wert="${gm.v}" clientWidth=${gm.b} scrollWidth=${gm.s} → ${gm.s <= gm.b ? 'VOLLSTAENDIG' : 'abgeschnitten'}`)

const v = s.locator('[data-probe="vorschau-block"]')
console.log(`Vorschau abgesetzt: ${await v.locator('.v2-divider').count() > 0 ? 'ja' : 'NEIN'}`)
console.log(`Spaltentrenner: ${await s.locator('[data-probe="spaltentrenner"]').count()}`)
console.log(`  ${JSON.stringify((await v.innerText()).replace(/\n/g, ' · '))}`)
await s.screenshot({ path: 'backup/g326-editor-nachher.png' })

console.log('\n── Portionen 2 → 4 ─────────────────────────')
const p = s.locator('input[aria-label="Portionen"]')
console.log(`vorher: ${JSON.stringify((await v.innerText()).split('\n').slice(0,2).join(' | '))}`)
await p.fill('4')
await s.waitForTimeout(700)
console.log(`nachher: ${JSON.stringify((await v.innerText()).replace(/\n/g, ' · '))}`)
await s.screenshot({ path: 'backup/g326-portionen4.png' })
await b.close()
