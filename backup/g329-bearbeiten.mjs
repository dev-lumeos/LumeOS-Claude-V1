import { chromium } from '@playwright/test'
import { wortFuer } from '../tools/konten.mjs'
const b = await chromium.launch()
const s = await b.newPage({ viewport: { width: 1440, height: 2400 } })
await s.goto('http://127.0.0.1:3200/login', { waitUntil: 'networkidle' })
await s.fill('input[type="email"]', 'dev@lumeos.app')
await s.fill('input[type="password"]', wortFuer('dev@lumeos.app'))
await s.click('button[type="submit"]')
await s.waitForURL(u => !u.pathname.includes('login'), { timeout: 30000 })
await s.goto('http://127.0.0.1:3200/v2/nutrition?tab=diary', { waitUntil: 'networkidle' })
await s.waitForTimeout(3000)

const zeilen = () => s.locator('[data-probe="ghost-zeile"]')
const vorher = await zeilen().count()
console.log(`Ghost-Zeilen vorher: ${vorher}`)

console.log('\n── entfernen ──')
await s.locator('[data-probe="ghost-entfernen"]').first().click()
await s.waitForTimeout(600)
console.log(`Zeilen: ${await zeilen().count()} (soll ${vorher - 1})`)
const hinweis = s.locator('[data-probe="ghost-entfernt-hinweis"]')
console.log(`Hinweis: ${JSON.stringify((await hinweis.first().innerText()).replace(/\n/g, ' '))}`)
await s.getByRole('button', { name: 'zurücknehmen' }).first().click()
await s.waitForTimeout(500)
console.log(`nach Zurücknehmen: ${await zeilen().count()} (soll ${vorher})`)

console.log('\n── hinzufügen ──')
await s.locator('[data-probe="ghost-zutat-suchen"]').first().click()
await s.waitForTimeout(900)
console.log(`Modal offen: ${await s.locator('[role="dialog"][aria-label="Lebensmittel suchen"]').count()}`)
console.log(`Sortierknöpfe: ${await s.locator('[role="dialog"] button[aria-pressed]').count()}`)
await s.fill('[role="dialog"] input[aria-label="Lebensmittel suchen"]', 'banane')
await s.waitForTimeout(2200)
await s.locator('[role="dialog"] tbody tr').first().locator('button').click()
await s.waitForTimeout(1200)
await s.locator('[role="dialog"] input[aria-label="Menge in Gramm"]').fill('120')
await s.waitForTimeout(500)
await s.locator('[role="dialog"]').getByRole('button', { name: 'Eintragen' }).click()
await s.waitForTimeout(1200)
console.log(`Zeilen: ${await zeilen().count()} (soll ${vorher + 1})`)
const neu = await zeilen().last().innerText()
console.log(`neue Zeile: ${JSON.stringify(neu.replace(/\n/g, ' | '))}`)

console.log('\n── MealCam ──')
await s.locator('[data-probe="ghost-mealcam"]').first().click()
await s.waitForTimeout(700)
const modal = await s.locator('[role="dialog"]').last().innerText().catch(() => '—')
console.log(`Vermerk: ${JSON.stringify(modal.replace(/\n/g, ' | ').slice(0, 420))}`)
await s.screenshot({ path: 'backup/g329-mealcam.png' })
await b.close()
